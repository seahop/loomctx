"""PROV-O export of an observation's provenance (D-050).

`observation_prov` renders one observation as a JSON-LD document in the W3C
PROV-O vocabulary, so a lineage tool can consume Loom's provenance without
learning Loom's contracts: the observation is a `prov:Entity` attributed to
its source (`prov:Agent`), generated at its observed time, derived from the
artifact span it cites when it has provenance, generated by an `extraction`
`prov:Activity` when a document was mined for it, and a `prov:wasRevisionOf`
the observation it supersedes — which in turn `prov:wasInvalidatedBy` that
supersession. Loom-specific fields (subject, predicate, object, confidence,
validity window) ride in the `loom:` namespace. The route is
`GET /v1/observations/{id}/prov`; the return shape is this plain dict, not
a contract model (docs/contracts.md).
"""

from __future__ import annotations

from datetime import datetime, timezone
from urllib.parse import quote

from .contracts import Artifact, EntityRef, Observation

CONTEXT = {
    "prov": "http://www.w3.org/ns/prov#",
    "xsd": "http://www.w3.org/2001/XMLSchema#",
    "loom": "urn:loom:",
}


def _time(value: datetime) -> dict:
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    return {"@value": value.isoformat(), "@type": "xsd:dateTime"}


def _iri(namespace: str, kind: str, key: str) -> str:
    return f"loom:{quote(namespace, safe='')}/{kind}/{quote(key, safe='')}"


def _object(obs: Observation):
    if isinstance(obs.object, EntityRef):
        return {"@id": _iri(obs.namespace, "entity", f"{obs.object.type}:{obs.object.key}")}
    return obs.object


def _is_extracted(obs: Observation) -> bool:
    return bool(obs.attrs.get("extracted")) or obs.source.startswith("doc:")


def observation_prov(obs: Observation, artifact: Artifact | None = None) -> dict:
    """The observation's provenance graph as JSON-LD (PROV-O). `artifact`,
    when the caller fetched the cited document, enriches the artifact node
    with its own attribution and time; without it the node is a bare
    reference, never invented."""
    ns = obs.namespace
    obs_iri = _iri(ns, "observation", obs.id)
    agent_iri = _iri(ns, "agent", obs.source)
    entity: dict = {
        "@id": obs_iri,
        "@type": "prov:Entity",
        "prov:generatedAtTime": _time(obs.observed_at),
        "prov:wasAttributedTo": {"@id": agent_iri},
        "loom:recordedAt": _time(obs.recorded_at),
        "loom:subject": {"@id": _iri(ns, "entity", f"{obs.subject.type}:{obs.subject.key}")},
        "loom:predicate": obs.predicate,
        "loom:object": _object(obs),
        "loom:confidence": obs.confidence,
    }
    if obs.event_id:
        entity["loom:eventId"] = obs.event_id
    if obs.valid_from is not None:
        entity["loom:validFrom"] = _time(obs.valid_from)
    if obs.valid_to is not None:
        entity["loom:validTo"] = _time(obs.valid_to)
    graph: list[dict] = [entity, {"@id": agent_iri, "@type": "prov:Agent", "loom:source": obs.source}]

    artifact_iri = None
    if obs.provenance is not None and obs.provenance.artifact_id:
        artifact_iri = _iri(ns, "artifact", obs.provenance.artifact_id)
        artifact_node: dict = {"@id": artifact_iri, "@type": "prov:Entity"}
        if artifact is not None and artifact.id == obs.provenance.artifact_id:
            artifact_node["prov:generatedAtTime"] = _time(artifact.observed_at)
            artifact_node["prov:wasAttributedTo"] = {"@id": _iri(ns, "agent", artifact.source)}
            artifact_node["loom:contentType"] = artifact.content_type
            if artifact.filename:
                artifact_node["loom:filename"] = artifact.filename
            graph.append({"@id": _iri(ns, "agent", artifact.source), "@type": "prov:Agent",
                          "loom:source": artifact.source})
        derived_from = artifact_iri
        span = obs.provenance
        if span.span_start is not None and span.span_end is not None:
            derived_from = f"{artifact_iri}#char={span.span_start},{span.span_end}"
            graph.append({
                "@id": derived_from, "@type": "prov:Entity",
                "prov:wasDerivedFrom": {"@id": artifact_iri},
                "loom:spanStart": span.span_start, "loom:spanEnd": span.span_end,
            })
        graph.append(artifact_node)
        entity["prov:wasDerivedFrom"] = {"@id": derived_from}

    if _is_extracted(obs):
        activity_iri = _iri(ns, "activity", f"extraction/{obs.id}")
        activity: dict = {"@id": activity_iri, "@type": "prov:Activity",
                          "loom:activity": "extraction", "prov:endedAtTime": _time(obs.recorded_at)}
        if artifact_iri is not None:
            activity["prov:used"] = {"@id": artifact_iri}
        model = obs.attrs.get("extractor_model") or obs.attrs.get("model")
        if isinstance(model, str) and model:
            model_iri = _iri(ns, "agent", f"model:{model}")
            activity["prov:wasAssociatedWith"] = {"@id": model_iri}
            graph.append({"@id": model_iri, "@type": ["prov:Agent", "prov:SoftwareAgent"],
                          "loom:model": model})
        entity["prov:wasGeneratedBy"] = {"@id": activity_iri}
        graph.append(activity)

    if obs.supersedes:
        old_iri = _iri(ns, "observation", obs.supersedes)
        supersession_iri = _iri(ns, "activity", f"supersession/{obs.id}")
        entity["prov:wasRevisionOf"] = {"@id": old_iri}
        graph.append({
            "@id": old_iri, "@type": "prov:Entity",
            "prov:wasInvalidatedBy": {"@id": supersession_iri},
            "prov:invalidatedAtTime": _time(obs.observed_at),
        })
        graph.append({
            "@id": supersession_iri, "@type": "prov:Activity", "loom:activity": "supersession",
            "prov:wasAssociatedWith": {"@id": agent_iri},
            "prov:used": {"@id": old_iri}, "prov:generated": {"@id": obs_iri},
            "prov:endedAtTime": _time(obs.observed_at),
        })

    return {"@context": CONTEXT, "@graph": graph}
